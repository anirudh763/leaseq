const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname, '../../leaseq/dashboard/assets/simulator.js'), 'utf8'), context);
const Q = context.window.LeaseQSimulator;
let checks = 0;
const check = (fn) => { fn(); checks++; };

check(() => assert.equal(Q.maxText, 10000));
check(() => assert.equal(Q.maxBatch, 10));
check(() => assert.throws(() => Q.enqueue(Q.fresh(''), 'x'.repeat(10001)), /at most 10,000/));
check(() => assert.throws(() => Q.enqueueBatch(Q.fresh(''), 'x', 11), /1 to 10/));
let m = Q.fresh('one two\nthree');
Q.enqueue(m); checks++;
Q.claim(m, 'worker-a'); checks++;
const token1 = m.job.token;
Q.heartbeat(m, 'worker-a'); checks++;
assert.equal(m.job.leaseExpiresAt, m.now + Q.leaseMs); checks++;
Q.crash(m, 'worker-a'); checks++;
Q.advance(m, Q.leaseMs + 1); checks++;
Q.claim(m, 'worker-b'); checks++;
const token2 = m.job.token;
check(() => assert.notEqual(token1, token2));
Q.complete(m, token1, 'worker-a'); checks++;
check(() => assert.equal(m.job.state, 'leased'));
Q.complete(m, token2, 'worker-b'); checks++;
check(() => assert.deepEqual(JSON.parse(JSON.stringify(m.job.result)), { words: 3, lines: 2 }));
check(() => assert.equal(Q.persistable(m).events.length, m.events.length));

m = Q.fresh('retry me'); Q.enqueue(m); Q.claim(m, 'worker-a');
Q.fail(m, m.job.token, 'worker-a');
check(() => assert.equal(m.job.state, 'queued'));
check(() => assert.throws(() => Q.claim(m, 'worker-b'), /No due/));
Q.advance(m, 1000); Q.claim(m, 'worker-b'); Q.fail(m, m.job.token, 'worker-b');
Q.advance(m, 2000); Q.claim(m, 'worker-a'); Q.fail(m, m.job.token, 'worker-a');
check(() => assert.equal(m.job.state, 'dead'));
Q.replay(m, 2); check(() => assert.equal(m.job.state, 'queued'));
check(() => assert.throws(() => Q.replay(m, 1), /Only a dead/));
Q.claim(m, 'worker-b'); Q.complete(m, m.job.token, 'worker-b');
check(() => assert.equal(m.job.state, 'done'));
m = Q.fresh('pause'); m.paused = true;
check(() => assert.throws(() => Q.enqueue(m), /paused/));
m = Q.fresh('x');
// Public operations are bounded by a single active job; event retention is capped.
m.events = Array.from({ length: 110 }, (_, i) => String(i)); Q.enqueue(m);
check(() => assert.equal(m.events.length, 100));
check(() => assert.equal(m.eventsDropped, 11));
check(() => assert.equal(Q.persistable(m).eventsDropped, 71));
const recovery = Q.runRecovery('alpha beta\ngamma');
check(() => assert.equal(recovery.job.state, 'done'));
check(() => assert.equal(recovery.job.attempts, 2));
check(() => assert(recovery.events.some((event) => /rejected/.test(event))));
check(() => assert.equal(Q.persistable(recovery).text, 'alpha beta\ngamma'));
const batch=Q.fresh('batch payload');Q.enqueueBatch(batch,'batch payload',4);
check(() => assert.deepEqual(JSON.parse(JSON.stringify(Q.counts(batch))),{total:4,queued:4,leased:0,done:0,dead:0}));
Q.claim(batch,'worker-a');Q.complete(batch,batch.job.token,'worker-a');Q.claim(batch,'worker-b');
check(() => assert.equal(batch.job.id,2));
check(() => assert.equal(Q.counts(batch).done,1));
while(Q.counts(batch).total<100)Q.enqueueBatch(batch,'bounded',Math.min(10,100-Q.counts(batch).total));
check(() => assert.throws(()=>Q.enqueueBatch(batch,'overflow',1),/at most 100/));
console.log(JSON.stringify({ checks }));
